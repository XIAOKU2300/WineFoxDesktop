<#
.SYNOPSIS
    WineFox sidecar packaging + optional Tauri shell / NSIS build.

.DESCRIPTION
    Produces, in order:
      1. dist\winefox-sidecar\  — PyInstaller onedir (windowed) sidecar
      2. src-tauri\binaries\winefox-sidecar.exe-x86_64-pc-windows-msvc.exe
         (externalBin input for `tauri build`; renamed to winefox-sidecar.exe)
      3. (optional) `tauri build` — WineFox.exe + NSIS installer
      4. packaging\nsis\generated_version.nsh for installer.nsi

    Policy: base package NEVER contains TensorFlow / Playwright Chromium /
    ComfyUI / models / CUDA.  No system-wide installs: everything goes into
    .build\venv.  Version equality (main == sidecar) is enforced.

.PARAMETER SourceDir
    Plugin source tree (defaults to source\astrbot_plugin_comfyui_pro_UltraPlusMax-master).

.PARAMETER Version
    Override app version (default: packaging\version.json "app").

.PARAMETER SkipTauri
    Do not run `tauri build` (Rust toolchain missing on this machine).

.PARAMETER SkipNsis
    Do not run NSIS makensis (portable NSIS missing).

.EXAMPLE
    .\packaging\build.ps1 -SourceDir D:\repo\astrbot_plugin_comfyui_pro_UltraPlusMax -SkipTauri
#>
[CmdletBinding()]
param(
    [string]$SourceDir = "",
    [string]$Version = "",
    [switch]$SkipTauri,
    [switch]$SkipNsis
)

$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $PSScriptRoot          # repo root
$Packaging = Join-Path $Root "packaging"
$Sidecar = Join-Path $Root "desktop_shell\sidecar"
$Tauri = Join-Path $Root "desktop_shell\src-tauri"
$BuildDir = Join-Path $Packaging ".build"

if (-not $SourceDir) {
    $SourceDir = $Root
}
if (-not (Test-Path $SourceDir)) {
    throw "Plugin source not found: $SourceDir (pass -SourceDir)"
}

# ---------------------------------------------------------------- version ----
$versions = Get-Content (Join-Path $Packaging "version.json") | ConvertFrom-Json
if (-not $Version) { $Version = $versions.app }
$VERSION = $Version
$PROTOCOL = $versions.protocol
Write-Host "== WineFox sidecar build v$VERSION (protocol $PROTOCOL) ==" -ForegroundColor Cyan

# ---------------------------------------------------------------- venv -------
$Venv = Join-Path $BuildDir "venv"
if (-not (Test-Path (Join-Path $Venv "Scripts\python.exe"))) {
    Write-Host "creating venv: $Venv"
    python -m venv $Venv
    & (Join-Path $Venv "Scripts\python.exe") -m pip install --upgrade pip
    & (Join-Path $Venv "Scripts\python.exe") -m pip install "pyinstaller>=6.16,<7"
}
$Py = Join-Path $Venv "Scripts\python.exe"
& $Py -m pip install -r (Join-Path $Packaging "pyinstaller\requirements-sidecar.txt")

# stamp sidecar version (single source of truth: packaging\version.json)
$VersionPy = Join-Path $Sidecar "winefox_sidecar\_version.py"
$VersionPyContent = @"
"""Version stamp for the WineFox desktop sidecar (auto-generated by build.ps1)."""

APP_VERSION = "$VERSION"
PROTOCOL = $PROTOCOL
IMPL_VERSION = "$($versions.sidecar_impl)"
"@
Set-Content -Path $VersionPy -Value $VersionPyContent -Encoding UTF8

# ---------------------------------------------------------------- version resource ----
$GenDir = Join-Path $Packaging "pyinstaller\generated"
New-Item -ItemType Directory -Force -Path $GenDir | Out-Null
$VerRes = Join-Path $GenDir "sidecar_version_file.txt"
$vparts = ($VERSION -split '\.') | ForEach-Object { [int]$_ } | Select-Object -First 4
while ($vparts.Count -lt 4) { $vparts += 0 }
$vf = ($vparts -join ', ')
$VerResContent = @"
# UTF-8
VSVersionInfo(
  ffi=FixedFileInfo(filevers=($vf), prodvers=($vf), mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo(
      [StringTable('040904B0', [StringStruct('CompanyName', 'WineFox'),
        StringStruct('FileDescription', 'WineFox desktop sidecar'),
        StringStruct('FileVersion', '$VERSION'),
        StringStruct('InternalName', 'winefox-sidecar'),
        StringStruct('OriginalFilename', 'winefox-sidecar.exe'),
        StringStruct('ProductName', 'WineFox'),
        StringStruct('ProductVersion', '$VERSION')])]
    ),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"@
Set-Content -Path $VerRes -Value $VerResContent -Encoding UTF8

# ---------------------------------------------------------------- pyinstaller ----
$env:WINE_FOX_PLUGIN_SRC = $SourceDir
Write-Host "== PyInstaller (onedir, windowed) ==" -ForegroundColor Cyan
& $Py -m PyInstaller --noconfirm --clean `
    (Join-Path $Packaging "pyinstaller\winefox-sidecar.spec") `
    --distpath (Join-Path $Packaging "dist") `
    --workpath (Join-Path $BuildDir "pyinstaller-work")
if ($LASTEXITCODE -ne 0) { throw "PyInstaller build failed (rc=$LASTEXITCODE)" }

$SidecarExe = Join-Path $Packaging "dist\winefox-sidecar\winefox-sidecar.exe"
if (-not (Test-Path $SidecarExe)) { throw "PyInstaller output missing: $SidecarExe" }

# ------------------------------------------------ selftest the packaged exe ----
Write-Host "== selftest packaged sidecar ==" -ForegroundColor Cyan
& $SidecarExe --version
$code = $LASTEXITCODE
if ($code -ne 0) { throw "packaged sidecar --version failed (rc=$code)" }
& $SidecarExe --selftest
if ($LASTEXITCODE -ne 0) { throw "packaged sidecar --selftest failed" }

# -------------------------------------------------- size policy verification ----
$sizeMB = [math]::Round((Get-ChildItem (Split-Path $SidecarExe) -Recurse | Measure-Object Length -Sum).Sum / 1MB, 1)
Write-Host "sidecar onedir size: ${sizeMB} MB (policy: no TF/Chromium/ComfyUI/models/CUDA)"
$forbidden = @("tensorflow", "torch", "playwright", "chromium", "opennsfw", "onnxruntime")
$dirty = Get-ChildItem (Split-Path $SidecarExe) -Recurse -File |
    Where-Object { $n = $_.Name.ToLower(); $forbidden | Where-Object { $n -like "*$_*" } } |
    Select-Object -ExpandProperty Name -Unique
if ($dirty) { Write-Warning "forbidden payload detected: $($dirty -join ', ')" }

# --------------------------------------- stage into src-tauri externalBin ----
$BinDir = Join-Path $Tauri "binaries"
New-Item -ItemType Directory -Force -Path $BinDir | Out-Null
Copy-Item $SidecarExe (Join-Path $BinDir "winefox-sidecar.exe-x86_64-pc-windows-msvc.exe") -Force
Copy-Item $SidecarExe (Join-Path $BinDir "winefox-sidecar.exe") -Force
Write-Host "staged -> $BinDir"

# ------------------------------------------------------------- tauri build ----
if (-not $SkipTauri) {
    Write-Host "== tauri build (requires Rust + tauri-cli) ==" -ForegroundColor Cyan
    $tauriCli = Join-Path $Root "desktop_shell\node_modules\.bin\tauri.cmd"
    if (Test-Path $tauriCli) {
        Push-Location $Tauri
        try {
            & $tauriCli build
            if ($LASTEXITCODE -ne 0) { throw "tauri build failed (rc=$LASTEXITCODE)" }
        } finally { Pop-Location }
    } elseif (Get-Command "cargo" -ErrorAction SilentlyContinue) {
        Write-Warning "tauri-cli missing; run: cd desktop_shell && npm i && npx tauri build"
    } else {
        Write-Warning "cargo not found; run: cd desktop_shell && npm i && npx tauri build"
    }
} else {
    Write-Host "(skipped tauri build)"
}

# ------------------------------------------------------------- NSIS ----
$NsisDefs = Join-Path $Packaging "nsis\generated_version.nsh"
@"
; auto-generated by build.ps1 - DO NOT EDIT
!define APP_VERSION "$VERSION"
!define SIDECAR_VERSION "$VERSION"
!define PROTOCOL_VERSION $PROTOCOL
"@ | Set-Content -Path $NsisDefs -Encoding ASCII

if (-not $SkipNsis) {
    $makensis = Get-Command "makensis.exe" -ErrorAction SilentlyContinue
    $makensisPath = if ($makensis) { $makensis.Source } else { "" }
    if (-not $makensisPath) {
        $portableRoot = Join-Path $Packaging ".build\nsis"
        $portableExe = Get-ChildItem -LiteralPath $portableRoot -Directory -Filter "nsis-*" -ErrorAction SilentlyContinue |
            Sort-Object Name -Descending |
            ForEach-Object { Join-Path $_.FullName "makensis.exe" } |
            Where-Object { Test-Path -LiteralPath $_ } |
            Select-Object -First 1
        if ($portableExe) { $makensisPath = $portableExe }
    }
    if ($makensisPath) {
        & (Join-Path $Packaging "nsis\build-nsis.ps1") -SidecarExe $SidecarExe -Makensis $makensisPath
        if ($LASTEXITCODE -ne 0) { throw "NSIS build failed (rc=$LASTEXITCODE)" }
    } else {
        Write-Warning "makensis not found; run packaging\nsis\build-nsis.ps1 or install NSIS"
    }
} else {
    Write-Host "(skipped NSIS)"
}

Write-Host "== done: WineFox v$VERSION ==" -ForegroundColor Green
